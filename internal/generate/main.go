// Command generate writes compose_generated.go from Unicode 17.0.0
// UnicodeData.txt, available at
// https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt.
//
//	go run ./internal/generate path/to/UnicodeData.txt > compose_generated.go
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

const inputSHA256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"

// marks are the combining characters produced by TeX accent commands.
var marks = map[rune]bool{
	0x0300: true, 0x0301: true, 0x0302: true, 0x0303: true, 0x0304: true,
	0x0306: true, 0x0307: true, 0x0308: true, 0x030A: true, 0x030B: true,
	0x030C: true, 0x0323: true, 0x0327: true, 0x0328: true, 0x0331: true,
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	const argumentCount = 2
	if len(os.Args) != argumentCount {
		return fmt.Errorf("usage: generate UnicodeData.txt")
	}
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		return err
	}
	sum := sha256.Sum256(data)
	if hex.EncodeToString(sum[:]) != inputSHA256 {
		return fmt.Errorf("unexpected UnicodeData.txt checksum %x", sum)
	}
	pairs, err := compositions(data)
	if err != nil {
		return err
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/generate from Unicode 17.0.0 UnicodeData.txt. DO NOT EDIT.\n\n")
	b.WriteString("package bibtex\n\nvar compositions = map[[2]rune]rune{\n")
	for _, p := range pairs {
		fmt.Fprintf(&b, "{0x%04X, 0x%04X}: 0x%04X,\n", p[0], p[1], p[2])
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	_, err = os.Stdout.Write(out)
	return err
}

// compositions returns canonical pairs of a letter and one of marks whose
// precomposed form is a Latin, Greek or Cyrillic letter.
func compositions(data []byte) ([][3]rune, error) {
	var pairs [][3]rune
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		f := strings.Split(sc.Text(), ";")
		if len(f) < 6 || !strings.HasPrefix(f[2], "L") || f[5] == "" || strings.HasPrefix(f[5], "<") {
			continue
		}
		const pair = 2
		parts := strings.Fields(f[5])
		if len(parts) != pair {
			continue
		}
		var vals [3]rune
		for i, s := range []string{parts[0], parts[1], f[0]} {
			v, err := strconv.ParseUint(s, 16, 32)
			if err != nil {
				return nil, err
			}
			vals[i] = rune(v)
		}
		if !marks[vals[1]] || vals[2] > 0x1EFF {
			continue
		}
		pairs = append(pairs, vals)
	}
	sort.Slice(pairs, func(i, j int) bool {
		if pairs[i][0] != pairs[j][0] {
			return pairs[i][0] < pairs[j][0]
		}
		return pairs[i][1] < pairs[j][1]
	})
	return pairs, sc.Err()
}
